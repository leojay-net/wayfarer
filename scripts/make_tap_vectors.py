"""Write the shared tap-protocol test vectors (tests/vectors/tap.json) from the Python reference implementation.

    python3 scripts/make_tap_vectors.py [--check]

Everything is deterministic (fixed clock, nonce, quote id, ML-DSA randomness). The Kotlin implementation must reproduce
these bytes and accept this envelope. ``--check`` fails if the committed file differs from a fresh run.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import sys
from decimal import Decimal
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))

from wayfarer.cheque import Cheque  # noqa: E402
from wayfarer.crypto import mldsa  # noqa: E402
from wayfarer.tap.envelope import ChequeEnvelope, cheque_for_request  # noqa: E402
from wayfarer.tap.link import encode_frames  # noqa: E402
from wayfarer.tap.merchant import MerchantTerminal  # noqa: E402
from wayfarer.tap.rates import FixedRateSource, RateDesk  # noqa: E402

OUT = ROOT / "tests" / "vectors" / "tap.json"
NOW_MS = 1_800_000_000_000
BUYER_SEED = bytes(range(31, 63))
VAULT = "buyer-vault.testnet"


def build() -> dict[str, object]:
    desk = RateDesk(FixedRateSource({("USD", "near"): Decimal("5000")}), lambda: NOW_MS, new_id=lambda: "q-test-0001")
    terminal = MerchantTerminal(
        account="cafe-shop.testnet",
        name="Sam's Cafe",
        rates=desk,
        clock_ms=lambda: NOW_MS,
        nonce_factory=lambda: bytes(range(16)),
    )
    request = terminal.create_request(150_000)  # USD 1,500.00
    cheque: Cheque = cheque_for_request(request, VAULT)
    public_key = mldsa.public_key_from_seed(BUYER_SEED)
    signature = mldsa.sign(BUYER_SEED, cheque.message(), randomness=bytes(32))
    envelope = ChequeEnvelope(
        request_hash=request.request_hash(),
        vault=VAULT,
        key_id=hashlib.sha256(public_key).digest(),
        signature=signature,
        public_key=public_key,
    )
    session = bytes([0xA1, 0xB2, 0xC3, 0xD4])
    return {
        "note": "Generated by scripts/make_tap_vectors.py. Deterministic. Test keys only.",
        "now_ms": NOW_MS,
        "rate_fiat_per_near": "5000",
        "buyer_seed": BUYER_SEED.hex(),
        "buyer_public_key_sha256": hashlib.sha256(public_key).hexdigest(),
        "vault": VAULT,
        "request": {
            "merchant_account": request.merchant_account,
            "merchant_name": request.merchant_name,
            "fiat_currency": request.fiat_currency,
            "fiat_minor": request.fiat_minor,
            "fiat_exponent": request.fiat_exponent,
            "token_id": request.token_id,
            "asset_amount": str(request.asset_amount),
            "quote_id": request.quote_id,
            "rate": request.rate,
            "quote_expires_ms": request.quote_expires_ms,
            "settle_by_ms": request.settle_by_ms,
            "nonce": request.nonce.hex(),
            "created_ms": request.created_ms,
        },
        "request_message_hex": request.message().hex(),
        "request_hash_hex": request.request_hash().hex(),
        "intent_id": request.intent_id(),
        "receipt_hash": request.receipt_hash(),
        "fiat_display": request.fiat_display(),
        "cheque_message_hex": cheque.message().hex(),
        "signature_hex": signature.hex(),
        "envelope_hex": envelope.encode().hex(),
        "envelope_frames": encode_frames(envelope.encode(), session),
        "request_frames": encode_frames(request.message(), session),
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    text = json.dumps(build(), indent=1) + "\n"
    if args.check:
        if OUT.read_text() != text:
            print(f"{OUT} is out of date; rerun without --check")
            return 1
        print("tap vectors are up to date")
        return 0
    OUT.write_text(text)
    print(f"wrote {OUT} ({OUT.stat().st_size} bytes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
